package com.bluetoothguardian.security

import androidx.compose.foundation.layout.*
import androidx.compose.foundation.lazy.LazyColumn
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Modifier
import androidx.compose.ui.unit.dp

/**
 * Evidence-led local device review. This is a checklist/rule-based helper,
 * not a vulnerability scanner and not a source of CVE truth.
 */
private data class ReviewSignal(
    val title: String,
    val detail: String,
    val checked: Boolean,
    val weight: Int
)

@Composable
fun DeviceIntelligence() {
    var vendor by remember { mutableStateOf("") }
    var model by remember { mutableStateOf("") }
    var firmware by remember { mutableStateOf("") }
    var firmwareKnown by remember { mutableStateOf(false) }
    var vendorPageChecked by remember { mutableStateOf(false) }
    var securityUpdatesKnown by remember { mutableStateOf(false) }
    var pairingReviewed by remember { mutableStateOf(false) }
    var unnecessaryServicesReviewed by remember { mutableStateOf(false) }
    var physicalAccessReviewed by remember { mutableStateOf(false) }
    var notes by remember { mutableStateOf("") }
    var generated by remember { mutableStateOf(false) }

    val signals = listOf(
        ReviewSignal("Firmware version verified", "Record the version from a trusted device/vendor source.", firmwareKnown, 20),
        ReviewSignal("Official vendor advisories checked", "Check the vendor's official support/security page manually.", vendorPageChecked, 25),
        ReviewSignal("Security update status known", "Confirm update availability and support lifecycle.", securityUpdatesKnown, 20),
        ReviewSignal("Pairing and bonding reviewed", "Review device settings and remove unknown trusted peers.", pairingReviewed, 15),
        ReviewSignal("Unused services reviewed", "Disable features only through the device owner's supported settings.", unnecessaryServicesReviewed, 10),
        ReviewSignal("Physical access considerations reviewed", "Consider reset, access, and recovery protections.", physicalAccessReviewed, 10)
    )
    val completed = signals.filter { it.checked }.sumOf { it.weight }
    val remaining = 100 - completed

    LazyColumn(
        modifier = Modifier.fillMaxSize(),
        contentPadding = PaddingValues(bottom = 24.dp),
        verticalArrangement = Arrangement.spacedBy(8.dp)
    ) {
        item {
            Text("DEVICE INTELLIGENCE", style = MaterialTheme.typography.titleLarge)
            Text("Local evidence checklist • no automatic CVE claims")
        }
        item {
            OutlinedTextField(vendor, { vendor = it }, label = { Text("Manufacturer / vendor") }, modifier = Modifier.fillMaxWidth())
        }
        item {
            OutlinedTextField(model, { model = it }, label = { Text("Model / product") }, modifier = Modifier.fillMaxWidth())
        }
        item {
            OutlinedTextField(firmware, { firmware = it }, label = { Text("Firmware version (if known)") }, modifier = Modifier.fillMaxWidth())
        }
        item {
            Text("Review completeness: $completed / 100")
            LinearProgressIndicator(progress = { completed / 100f }, modifier = Modifier.fillMaxWidth())
            Text("Remaining review items: $remaining")
            Text("This is checklist completion, NOT a device security score or proof of safety.")
        }
        items(signals.size) { index ->
            val signal = signals[index]
            val checked = when (index) {
                0 -> firmwareKnown
                1 -> vendorPageChecked
                2 -> securityUpdatesKnown
                3 -> pairingReviewed
                4 -> unnecessaryServicesReviewed
                else -> physicalAccessReviewed
            }
            Card(Modifier.fillMaxWidth()) {
                Column(Modifier.padding(12.dp)) {
                    Row(verticalAlignment = androidx.compose.ui.Alignment.CenterVertically) {
                        Checkbox(checked, { value ->
                            when (index) {
                                0 -> firmwareKnown = value
                                1 -> vendorPageChecked = value
                                2 -> securityUpdatesKnown = value
                                3 -> pairingReviewed = value
                                4 -> unnecessaryServicesReviewed = value
                                else -> physicalAccessReviewed = value
                            }
                        })
                        Column(Modifier.weight(1f)) {
                            Text(signal.title, style = MaterialTheme.typography.titleMedium)
                            Text(signal.detail, style = MaterialTheme.typography.bodySmall)
                        }
                    }
                }
            }
        }
        item {
            OutlinedTextField(
                value = notes,
                onValueChange = { notes = it },
                label = { Text("Evidence / source notes (avoid secrets)") },
                modifier = Modifier.fillMaxWidth(),
                minLines = 3
            )
        }
        item {
            Button(
                enabled = vendor.isNotBlank() && model.isNotBlank(),
                onClick = { generated = true }
            ) { Text("Generate local review summary") }
        }
        if (generated) {
            item {
                Card(Modifier.fillMaxWidth()) {
                    Column(Modifier.padding(12.dp)) {
                        Text("LOCAL REVIEW SUMMARY", style = MaterialTheme.typography.titleMedium)
                        Text("Vendor: $vendor")
                        Text("Model: $model")
                        Text("Firmware: ${firmware.ifBlank { "Not provided" }}")
                        Text("Checklist completion: $completed%")
                        Text("Unverified items are unknown—not automatically vulnerabilities.")
                        Text("Notes: $notes")
                        Text("No CVE match, exploitability, or safety certification is asserted.")
                    }
                }
            }
        }
    }
}
